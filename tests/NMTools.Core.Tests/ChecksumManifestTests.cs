using NMTools.Core.Updates;

namespace NMTools.Core.Tests;

public sealed class ChecksumManifestTests
{
    private const string HashA = "7abf9fa8b762fa50fb1d4d1cfb40e49017a892295ac71e2f5fc9d5b2d2bbe340";
    private const string HashB = "d65e08cd644c85d08a4f624b77a5624484b4769acab68289c6aec57d622da22e";

    [Fact]
    public void Parse_ReadsStandardChecksumLines()
    {
        var text = $"""
        {HashA}  NMTools-v0.8.0-win-x64.zip
        {HashB} *NMTools-v0.8.1-win-x64.zip
        """;

        var manifest = ChecksumManifest.Parse(text);

        Assert.Equal(2, manifest.Count);
        Assert.Equal(HashA, manifest["NMTools-v0.8.0-win-x64.zip"]);
        // 二进制模式标记 "*" 后面的文件名要能正确取出。
        Assert.Equal(HashB, manifest["NMTools-v0.8.1-win-x64.zip"]);
    }

    [Fact]
    public void Parse_NormalizesHashToLowercase()
    {
        var manifest = ChecksumManifest.Parse($"{HashA.ToUpperInvariant()}  file.zip");

        Assert.Equal(HashA, manifest["file.zip"]);
    }

    [Fact]
    public void Parse_IgnoresCommentsAndBlankLines()
    {
        var text = $"""
        # generated by publish script

        {HashA}  file.zip

        """;

        var manifest = ChecksumManifest.Parse(text);

        Assert.Single(manifest);
    }

    [Theory]
    [InlineData("not-a-hash  file.zip")]
    [InlineData("abc123  file.zip")]
    [InlineData("")]
    [InlineData("   ")]
    [InlineData(null)]
    [InlineData("7abf9fa8b762fa50fb1d4d1cfb40e49017a892295ac71e2f5fc9d5b2d2bbe34")]
    public void Parse_RejectsMalformedInput(string? text)
    {
        Assert.Empty(ChecksumManifest.Parse(text));
    }

    [Fact]
    public void Parse_IgnoresLineWithHashButNoFileName()
    {
        Assert.Empty(ChecksumManifest.Parse(HashA));
    }

    [Fact]
    public void Parse_BadLineDoesNotBreakGoodLines()
    {
        // 一个无关文件写错格式，不该让整份清单失效。
        var text = $"""
        garbage line here
        {HashA}  good.zip
        """;

        var manifest = ChecksumManifest.Parse(text);

        Assert.Single(manifest);
        Assert.Equal(HashA, manifest["good.zip"]);
    }

    [Fact]
    public void Parse_StripsPathFromEntryName()
    {
        // 清单里写相对路径时只取文件名，避免查找错位。
        var manifest = ChecksumManifest.Parse($"{HashA}  some/dir/file.zip");

        Assert.Equal(HashA, manifest["file.zip"]);
    }

    [Fact]
    public void FindChecksum_IsCaseInsensitiveOnFileName()
    {
        var manifest = ChecksumManifest.Parse($"{HashA}  NMTools.zip");

        Assert.Equal(HashA, ChecksumManifest.FindChecksum(manifest, "nmtools.ZIP"));
    }

    [Fact]
    public void FindChecksum_ReturnsNullWhenMissing()
    {
        var manifest = ChecksumManifest.Parse($"{HashA}  other.zip");

        Assert.Null(ChecksumManifest.FindChecksum(manifest, "missing.zip"));
    }

    [Theory]
    [InlineData(HashA, HashA, true)]
    [InlineData(HashA, HashB, false)]
    [InlineData(HashA, null, false)]
    [InlineData(null, HashA, false)]
    [InlineData("", "", false)]
    public void Matches_ComparesCaseInsensitively(string? expected, string? actual, bool shouldMatch)
    {
        Assert.Equal(shouldMatch, ChecksumManifest.Matches(expected, actual));
    }

    [Fact]
    public void Matches_IgnoresHashCasing()
    {
        Assert.True(ChecksumManifest.Matches(HashA, HashA.ToUpperInvariant()));
        Assert.True(ChecksumManifest.Matches(HashA.ToUpperInvariant(), HashA));
    }

    [Fact]
    public void FormatEntry_ProducesParseableLine()
    {
        var line = ChecksumManifest.FormatEntry(HashA, "NMTools-v0.8.0-win-x64.zip");
        var parsed = ChecksumManifest.Parse(line);

        Assert.Equal(HashA, parsed["NMTools-v0.8.0-win-x64.zip"]);
    }
}
